-- =========================================================================
-- 31. PUBLICATION SETUP (REALTIME PUSH NOTIFICATION)
-- =========================================================================
-- Mengaktifkan realtime agar push notification dan chat berjalan secara instan.
-- Kita bungkus dengan pengecekan aman agar tidak menghasilkan error duplikat.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime'
  ) THEN
    CREATE PUBLICATION supabase_realtime;
  END IF;
  
  -- Menambahkan tabel notifications ke publication secara aman
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE notifications;
  EXCEPTION
    WHEN duplicate_object THEN
      NULL; -- abaikan jika sudah ditambahkan
  END;

  -- Menambahkan tabel community_messages ke publication secara aman
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE community_messages;
  EXCEPTION
    WHEN duplicate_object THEN
      NULL; -- abaikan jika sudah ditambahkan
  END;
END $$;
