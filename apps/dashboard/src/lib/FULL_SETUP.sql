-- 2. TABEL PROFIL PENGGUNA (Terhubung ke Supabase Auth.users)
CREATE TABLE IF NOT EXISTS profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  full_name TEXT,
  username TEXT UNIQUE,
  avatar_url TEXT,
  role TEXT DEFAULT 'student',
  friend_code TEXT UNIQUE DEFAULT substring(md5(random()::text) from 1 for 6),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 3. TABEL KURSUS (Courses)
CREATE TABLE IF NOT EXISTS courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  instructor TEXT NOT NULL,
  instructor_id UUID REFERENCES profiles(id) ON DELETE SET NULL,
  price DECIMAL NOT NULL,
  image_url TEXT,
  category TEXT,
  description TEXT,
  status TEXT DEFAULT 'draft',
  level TEXT DEFAULT 'beginner',
  language TEXT DEFAULT 'id',
  what_will_learn JSONB,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 4. TABEL ENROLLMENT (Pembelian / Pendaftaran Kursus)
