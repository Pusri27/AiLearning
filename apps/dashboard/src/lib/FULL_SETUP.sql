-- RPC: Bergabung ke Komunitas dengan Kode Undangan
CREATE OR REPLACE FUNCTION join_community(invite_code_input TEXT)
RETURNS UUID AS $$
DECLARE
  target_comm_id UUID;
BEGIN
  SELECT id INTO target_comm_id FROM communities WHERE invite_code = invite_code_input;
  
  IF target_comm_id IS NULL THEN
    RETURN NULL;
  END IF;

  INSERT INTO community_members (community_id, user_id, role)
  VALUES (target_comm_id, auth.uid(), 'member')
  ON CONFLICT (community_id, user_id) DO NOTHING;

  RETURN target_comm_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- RPC: Tambah Teman Menggunakan Friend Code
CREATE OR REPLACE FUNCTION add_friend_by_code(friend_code_input TEXT)
RETURNS BOOLEAN AS $$
DECLARE
  target_user_id UUID;
BEGIN
  SELECT id INTO target_user_id FROM profiles WHERE friend_code = friend_code_input;
  
  IF target_user_id IS NULL OR target_user_id = auth.uid() THEN
    RETURN FALSE;
  END IF;

  INSERT INTO friends (user_id, friend_id)
  VALUES (auth.uid(), target_user_id)
  ON CONFLICT (user_id, friend_id) DO NOTHING;

  INSERT INTO friends (user_id, friend_id)
  VALUES (target_user_id, auth.uid())
  ON CONFLICT (user_id, friend_id) DO NOTHING;

  RETURN TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Helper: Mengecek apakah pengguna adalah manager komunitas
CREATE OR REPLACE FUNCTION is_community_manager(comm_id UUID, u_id UUID) 
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM community_members 
    WHERE community_id = comm_id AND user_id = u_id AND role IN ('owner', 'admin')
  );
END;
$$ LANGUAGE plpgsql;


